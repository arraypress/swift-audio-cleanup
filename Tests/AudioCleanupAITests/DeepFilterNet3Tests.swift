import Foundation
import Testing
@testable import AudioCleanupAI

private func loadFloats(_ name: String) throws -> [Float] {
    let url = try #require(Bundle.module.url(forResource: name, withExtension: "bin"))
    return try Data(contentsOf: url).withUnsafeBytes { Array($0.bindMemory(to: Float.self)) }
}

private func rms(_ x: ArraySlice<Float>) -> Float {
    x.isEmpty ? 0 : (x.reduce(0) { $0 + $1 * $1 } / Float(x.count)).squareRoot()
}

@Suite("DeepFilterNet3", .serialized)
struct DeepFilterNet3Tests {

    /// The Swift vDSP pipeline must reproduce the numpy/libdf-verified golden
    /// output (`fixture_out.bin`) generated by the exact same recipe — STFT,
    /// ERB features, both exponential normalizers, Core ML forward, ERB gains +
    /// 5-tap complex deep filter, ISTFT. Any layout/formula error collapses SNR.
    @Test("Matches the libdf-verified golden output")
    func matchesGolden() throws {
        let input = try loadFloats("fixture_in")
        let expected = try loadFloats("fixture_out")
        let engine = try DeepFilterNet3()
        let output = try engine.enhance(input)

        let n = min(output.count, expected.count)
        #expect(n > 40_000)
        var noise: Float = 0, signal: Float = 0
        for i in 0..<n {
            let d = output[i] - expected[i]
            noise += d * d
            signal += expected[i] * expected[i]
        }
        let snr = 10 * log10(signal / max(noise, 1e-12))
        #expect(snr > 25, "SNR vs golden = \(snr) dB (expect high; low = a DSP/layout bug)")
    }

    /// Independent of the golden: the pass should reduce broadband energy on a
    /// noisy input while preserving length.
    @Test("Denoises and preserves length")
    func denoises() throws {
        let input = try loadFloats("fixture_in")
        let engine = try DeepFilterNet3()
        let output = try engine.enhance(input)
        #expect(output.count == input.count)
        #expect(rms(output[...]) < rms(input[...]))
    }

    /// The public reducer at 48 kHz is a straight pass through the engine.
    @Test("Reducer preserves channel length at 48 kHz")
    func reducerRoundTrip() throws {
        let input = try loadFloats("fixture_in")
        var channels = [input]
        DeepFilterNetReducer().reduce(&channels, sampleRate: 48_000, progress: nil)
        #expect(channels.count == 1)
        #expect(channels[0].count == input.count)
    }
}
